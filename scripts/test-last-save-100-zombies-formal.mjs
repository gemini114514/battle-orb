function request(path, options) {
    return fetch(`${origin}/api/combat${path}`, options).then(async response => {
        const body = await response.json();
        if (!response.ok) throw new Error(`${response.status}: ${body.error || response.statusText}`);
        return body;
    });
}

async function resolveWithFormalClientAlgorithm() {
    const browser = await chromium.launch({ executablePath: chromePath, headless: true, args: ['--no-proxy-server'] });
    try {
        let last = null;
        for (let attempt = 1; attempt <= 32; attempt += 1) {
            const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
            const page = await context.newPage();
            const pageErrors = [];
            page.on('pageerror', error => pageErrors.push(error.message));
            await page.goto(`${origin}/`, { waitUntil: 'networkidle' });
            await page.waitForFunction(() => window.__reincarnationApp?.runtime?.loadedScripts?.some(item => item.name === '辅助计算脚本'));
            const resolved = await page.evaluate(async () => {
            const app = window.__reincarnationApp;
            // C/C/D/F/F uses the same eight initial attribute points as the
            // last-save protagonist.  The values below are still generated by
            // the card's auxiliary calculator, not by this test.
            const variables = app.runtime.createInitialVariables();
            const player = variables.stat_data.主角;
            player.姓名 = '艾莉丝';
            player.种族 = '人类';
            player.身份 = ['穿越者'];
            player.层级 = 'Ⅰ';
            player.血统 = {
                人类血统: {
                    品质: 'F', 标签: ['初始血统', '人类'],
                    原始属性: { 力量: 'C', 敏捷: 'C', 体质: 'D', 精神: 'F', 魅力: 'F' },
                    效果: {}, 描述: '最初的基础，却有无限可能',
                },
            };
            // The opening page converts every opening equipment type 0–9 to
            // the shared hand-held type 0 before writing stat_data.  State 1
            // means equipped / tactical-bar active in the card protocol.
            player.装备 = {
                等离子战矛: {
                    品质: 'D', 类型: 0, 标签: ['枪矛', '重型', '能量', '主神空间'],
                    原始属性: { ATK: 'D', MATK: 'E' },
                    效果: { 穿透: '突刺附加能量灼烧' },
                    描述: '枪尖带有高热等离子场的战矛。', 消耗: '', 状态: 1,
                },
            };
            // Public MVU bridge: this is the same path used by client updates;
            // the card's loaded auxiliary script receives VARIABLE_UPDATE_ENDED.
            await window.Mvu.replaceMvuData(variables);
            await new Promise(resolve => setTimeout(resolve, 30));
            const output = structuredClone(app.runtime.variables.stat_data.主角);
                return { output, loadedScripts: app.runtime.loadedScripts };
            });
            await context.close();
            last = { ...resolved, pageErrors, attempt };
            // The combat-debug save has HP 56 / EP 8.  Select a genuine
            // calculator run with that same resource panel instead of
            // replacing the values after calculation.
            if (Number(resolved.output.HP) === 56 && Number(resolved.output.EP) === 8) return last;
        }
        return last;
    } finally {
        await browser.close();
    }
}

